package org.pih.warehouse.regression.apidocs

import grails.util.GrailsNameUtils
import org.yaml.snakeyaml.DumperOptions
import org.yaml.snakeyaml.Yaml

/**
 * Writes a stub OpenAPI operation for every inventory route that the spec does not document yet.
 *
 * Curated entries (x-doc-status other than "stub") are never rewritten: a tag file holding only
 * stubs is regenerated in full, a tag file holding curated entries only gets new path items
 * appended as text. The paths section of openapi.yaml between the generated-paths markers is
 * rewritten to $ref every path item.
 */
class ApiDocsStubGenerator {

    static final String BEGIN_MARKER = '  # BEGIN GENERATED PATHS'
    static final String END_MARKER = '  # END GENERATED PATHS'

    static final String FILE_HEADER = '''\
# Generated by the apiDocsGenerate task from the route inventory.
# Entries with x-doc-status: stub are regenerated; change x-doc-status to curated (or complete)
# before editing an entry by hand, and the generator will leave it alone.
'''

    /** Session operations that work without logging in (SecurityInterceptor lets them through). */
    static final Set<String> PUBLIC_OPERATIONS = ['api/login', 'api/logout', 'api/status'] as Set

    final File dir
    final List<ApiRoute> routes
    List<String> messages = []
    /** Changes the generator could not make without rewriting curated entries. */
    List<String> manualSteps = []

    /**
     * When true (apiDocs.prune), curated operations that no OBAF route answers are removed, and a curated
     * operation routed to another action on OBAF gets OBAF's controller/action plus an x-obaf-note. Every change is listed in {@link #pruned}.
     */
    boolean prune = false
    List<String> pruned = []

    ApiDocsStubGenerator(File dir, List<ApiRoute> routes) {
        this.dir = dir
        this.routes = routes
    }

    void generate() {
        File pathsDir = new File(dir, 'paths')
        pathsDir.mkdirs()

        // Where each path currently lives, and what each tag file holds.
        Map<String, Map> fileContents = [:]
        Map<String, String> pathToFile = [:]
        pathsDir.listFiles().findAll { it.name.endsWith('.yaml') }.sort { it.name }.each { File f ->
            Map content = (Map) new Yaml().load(f.text) ?: [:]
            fileContents["paths/${f.name}".toString()] = content
            content.keySet().each { String path -> pathToFile[path] = "paths/${f.name}".toString() }
        }

        // Existing ids stay put (curated ones and stubs alike); only new operations get new ids.
        Map<String, String> existingIds = [:]
        fileContents.values().each { Map content ->
            content.each { String path, Map item ->
                item.each { String method, Object op ->
                    if (op instanceof Map && op.operationId) {
                        existingIds["${method.toUpperCase()} ${path}".toString()] = (String) op.operationId
                    }
                }
            }
        }
        Map<String, String> operationIds = operationIds(routes, existingIds)
        Map<String, List<ApiRoute>> routesByPath = routes.groupBy { it.path }
        routesByPath.each { String path, List<ApiRoute> pathRoutes ->
            pathToFile.putIfAbsent(path, "paths/${fileName(pathRoutes.min().controller)}.yaml".toString())
        }

        Map<String, List<String>> pathsByFile = pathToFile.keySet().groupBy { pathToFile[it] }
        pathsByFile.each { String file, List<String> paths ->
            Map existing = fileContents[file] ?: [:]
            boolean hasCurated = existing.values().any { Map item ->
                item.any { String method, Object op -> op instanceof Map && op[OpenApiDocument.STATUS] != OpenApiDocument.STATUS_STUB }
            }
            File target = new File(dir, file)
            if (!hasCurated) {
                Map content = new LinkedHashMap()
                paths.findAll { routesByPath[it] }.sort().each { String path ->
                    content[path] = pathItem(routesByPath[path], operationIds)
                }
                if (content) {
                    writeIfChanged(target, FILE_HEADER + dump(content))
                } else if (target.exists()) {
                    target.delete()
                    messages << "removed ${file} (no routes left)"
                }
            } else {
                // Curated entries stay as they are; stub entries are regenerated like in any other file, so a
                // change to the stub template reaches them too.
                Map content = new LinkedHashMap()
                (existing.keySet() + paths).unique().sort().each { String path ->
                    Map item = (Map) existing[path]
                    List<ApiRoute> pathRoutes = routesByPath[path] ?: []
                    if (item == null) {
                        if (pathRoutes) {
                            content[path] = pathItem(pathRoutes, operationIds)
                        }
                        return
                    }
                    Map updated = new LinkedHashMap()
                    item.each { String method, Object op ->
                        ApiRoute route = pathRoutes.find { it.method.toLowerCase() == method }
                        boolean isStub = op instanceof Map && op[OpenApiDocument.STATUS] == OpenApiDocument.STATUS_STUB
                        if (prune && method in OpenApiDocument.HTTP_METHODS && !route) {
                            pruned << "${file}: removed ${method.toUpperCase()} ${path} (${isStub ? 'stub' : op?.get(OpenApiDocument.STATUS)}; no OBAF route)".toString()
                            return
                        }
                        if (prune && route && !isStub && op instanceof Map &&
                                "${op['x-openboxes-controller']}/${op['x-openboxes-action']}" != route.target) {
                            String was = "${op['x-openboxes-controller']}/${op['x-openboxes-action']}"
                            Map retargeted = new LinkedHashMap((Map) op)
                            retargeted['x-openboxes-controller'] = route.controller
                            retargeted['x-openboxes-action'] = route.action
                            retargeted['x-obaf-note'] = "OBAF routes this to ${route.target}; previously documented as ${was}".toString()
                            pruned << "${file}: ${method.toUpperCase()} ${path} retargeted ${was} -> ${route.target}".toString()
                            updated[method] = retargeted
                            return
                        }
                        if (isStub && route) {
                            updated[method] = stub(route, operationIds[route.key])
                        } else {
                            if (isStub) {
                                manualSteps << "${file}: remove stale stub ${method.toUpperCase()} ${path} by hand"
                            }
                            updated[method] = op
                        }
                    }
                    pathRoutes.findAll { !item.containsKey(it.method.toLowerCase()) }.each { ApiRoute route ->
                        updated[route.method.toLowerCase()] = stub(route, operationIds[route.key])
                    }
                    if (updated.keySet().any { it in OpenApiDocument.HTTP_METHODS }) {
                        content[path] = updated
                    }
                }
                fileContents[file] = content
                if (content) {
                    writeIfChanged(target, FILE_HEADER + dump(content))
                } else if (target.exists()) {
                    target.delete()
                    messages << "removed ${file} (no routes left)"
                }
            }
        }

        // Keep only paths that still exist in some tag file.
        Map<String, String> refs = new TreeMap<String, String>()
        pathToFile.each { String path, String file ->
            Map item = (Map) fileContents[file]?.get(path)
            boolean curated = item?.any { String method, Object op -> op instanceof Map && op[OpenApiDocument.STATUS] != OpenApiDocument.STATUS_STUB }
            if (routesByPath[path] || curated) {
                refs[path] = file
            }
        }
        writePathsSection(refs)
    }

    private static Map pathItem(List<ApiRoute> pathRoutes, Map<String, String> operationIds) {
        Map item = new LinkedHashMap()
        pathRoutes.sort().each { ApiRoute r ->
            item[r.method.toLowerCase()] = stub(r, operationIds[r.key])
        }
        item
    }

    static Map stub(ApiRoute r, String operationId) {
        Map op = new LinkedHashMap()
        op.operationId = operationId
        op.summary = "${r.controller}.${r.action}".toString()
        op.tags = [tagName(r.controller)]
        op[OpenApiDocument.STATUS] = OpenApiDocument.STATUS_STUB
        op['x-openboxes-controller'] = r.controller
        op['x-openboxes-action'] = r.action
        op['x-openboxes-source'] = r.source.name().toLowerCase()
        if (r.formatSuffix) {
            op['x-openboxes-format-suffix'] = true
            op.description = 'Also accepts a format suffix on the path, e.g. `.csv`.'
        }
        if (r.source == ApiRoute.Source.GENERIC) {
            op['x-openboxes-free-form'] = true
        }
        if (r.target in PUBLIC_OPERATIONS) {
            op.security = []
        }
        if (r.pathParams) {
            op.parameters = r.pathParams.collect { String name ->
                [name: name, in: 'path', required: true, schema: [type: 'string']]
            }
        }
        if (r.method in ['POST', 'PUT', 'PATCH']) {
            op.requestBody = ['$ref': '../components/request-bodies.yaml#/StubBody']
        }
        // The success statuses an undocumented operation may answer: 200 always, 201 for POST, 204 for every
        // method with side effects. Anything else is an error (default).
        Map responses = ['200': ['$ref': '../components/responses.yaml#/StubSuccess']]
        if (r.method == 'POST') {
            responses['201'] = ['$ref': '../components/responses.yaml#/StubCreated']
        }
        if (r.method in ['POST', 'PUT', 'PATCH', 'DELETE']) {
            responses['204'] = ['$ref': '../components/responses.yaml#/StubNoContent']
        }
        responses['default'] = ['$ref': '../components/responses.yaml#/Error']
        op.responses = responses
        op
    }

    /**
     * Operation ids: an operation that already has one keeps it. A new operation gets
     * controller_action, disambiguated with the method and then a counter when that id is taken.
     */
    static Map<String, String> operationIds(List<ApiRoute> routes, Map<String, String> existing = [:]) {
        Map<String, String> ids = [:]
        Set<String> taken = new HashSet<String>(existing.values())
        routes.sort().each { ApiRoute r ->
            if (existing[r.key]) {
                ids[r.key] = existing[r.key]
                return
            }
            String base = "${r.controller}_${r.action}".toString()
            String id = base in taken ? "${base}_${r.method.toLowerCase()}".toString() : base
            String unique = id
            for (int n = 2; unique in taken; n++) {
                unique = "${id}_${n}".toString()
            }
            ids[r.key] = unique
            taken << unique
        }
        ids
    }

    static String tagName(String controller) {
        switch (controller) {
            case 'api': return 'Session'
            case 'genericApi': return 'Generic'
            default: return GrailsNameUtils.getNaturalName(controller - ~/Api$/)
        }
    }

    static String fileName(String controller) {
        tagName(controller).toLowerCase().replace(' ', '-')
    }

    private void writePathsSection(Map<String, String> refs) {
        File rootFile = new File(dir, 'openapi.yaml')
        String text = rootFile.text
        int begin = text.indexOf(BEGIN_MARKER)
        int end = text.indexOf(END_MARKER)
        if (begin < 0 || end < begin) {
            throw new IllegalStateException("openapi.yaml must contain the lines '${BEGIN_MARKER.trim()}' and '${END_MARKER.trim()}' under paths:")
        }
        StringBuilder section = new StringBuilder(BEGIN_MARKER).append('\n')
        refs.each { String path, String file ->
            section.append("  '${path}':\n    \$ref: '${file}#${OpenApiDocument.pointerFor(path)}'\n")
        }
        writeIfChanged(rootFile, text.substring(0, begin) + section + text.substring(end))
    }

    private void writeIfChanged(File file, String content) {
        if (!file.exists() || file.text != content) {
            file.text = content
            messages << "wrote ${dir.toPath().relativize(file.toPath())}"
        }
    }

    static String dump(Map content) {
        DumperOptions options = new DumperOptions()
        options.defaultFlowStyle = DumperOptions.FlowStyle.BLOCK
        options.indent = 2
        options.indicatorIndent = 0
        options.width = 200
        options.splitLines = false
        new Yaml(options).dump(content)
    }
}
